import { useEffect, useState } from 'react';

// Optional per-player extras from public/data/player-extras.json (built by scripts/build_league_data.py).
// Everything here is secondary display info and must never be merged into league career totals.

/** Pre-league real NFL career line. Keys vary by position; `years` is e.g. "2018-2025". */
export type RealNflCareer = { years?: string } & Record<string, number | string | undefined>;

/** In-game player card extras; any subset of keys may be present. */
export type PlayerCardExtras = Record<string, number | string | boolean | undefined>;

/** One reconstructed career stop (data/y80/stints.json). Years are save seasons (Y1–Y80; Y81 = joined after Y80). */
export interface CareerStint {
  team: string;
  from: number;
  to: number;
  /** Super Bowl years won during this stint */
  rings: number[];
}

export type StintConfidence = 'confirmed' | 'strong' | 'likely' | 'ambiguous';

export interface PlayerStints {
  stints: CareerStint[];
  confidence: StintConfidence;
  evidence: string;
  /** Years are a placeholder; only the team is known */
  approx?: boolean;
  /** Real-NFL rings on his card, won before the save */
  preLeagueRings?: number;
  alternatives?: { team: string; from: number; to: number }[][];
}

export interface PlayerExtras {
  realNflCareer: Record<string, RealNflCareer>;
  cards: Record<string, PlayerCardExtras>;
  /** current name -> former name */
  formerNames: Record<string, string>;
  /** player name -> relation text, e.g. "son of Tyrion Kline" */
  family: Record<string, string>;
  /** player name -> every franchise he played for (full names), when more than his final team is known */
  franchises: Record<string, string[]>;
  /** player name -> reconstructed career stints, in order */
  stints: Record<string, PlayerStints>;
  /**
   * player name -> the franchise he is best known for (full name): his card / banner identity (jersey, helmet,
   * colours, logo). Generated by scripts/build_league_data.py (owner fact, else the stint with the most rings).
   */
  signatureTeams: Record<string, string>;
}

const EMPTY: PlayerExtras = { realNflCareer: {}, cards: {}, formerNames: {}, family: {}, franchises: {}, stints: {}, signatureTeams: {} };

/** Name key that ignores case, extra spaces and curly vs straight apostrophes/quotes. */
export const normalizeName = (name: string) =>
  name
    .replace(/[‘’ʼ`´]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();

const reindex = <T,>(rec: unknown): Record<string, T> => {
  const out: Record<string, T> = {};
  if (rec && typeof rec === 'object') {
    Object.entries(rec as Record<string, T>).forEach(([k, v]) => {
      out[normalizeName(k)] = v;
    });
  }
  return out;
};

/** Original-cased map, keyed by normalized name (used where the display name matters). */
const reindexWithName = (rec: unknown): Record<string, { name: string; value: string }> => {
  const out: Record<string, { name: string; value: string }> = {};
  if (rec && typeof rec === 'object') {
    Object.entries(rec as Record<string, unknown>).forEach(([k, v]) => {
      if (typeof v === 'string') out[normalizeName(k)] = { name: k, value: v };
    });
  }
  return out;
};

export interface IndexedExtras {
  realNflCareer: Record<string, RealNflCareer>;
  cards: Record<string, PlayerCardExtras>;
  formerNames: Record<string, string>;
  family: Record<string, { name: string; value: string }>;
  franchises: Record<string, string[]>;
  stints: Record<string, PlayerStints>;
  signatureTeams: Record<string, string>;
}

const CONFIDENCE = new Set<StintConfidence>(['confirmed', 'strong', 'likely', 'ambiguous']);

/** Keeps only well-formed stint records (a bad row is dropped, never thrown). */
const normalizeStints = (rec: unknown): Record<string, PlayerStints> => {
  const out: Record<string, PlayerStints> = {};
  Object.entries(reindex<Partial<PlayerStints>>(rec)).forEach(([k, v]) => {
    const stints = (Array.isArray(v?.stints) ? v.stints : [])
      .filter((s): s is CareerStint => !!s && typeof s.team === 'string' && Number.isFinite(s.from) && Number.isFinite(s.to))
      .map((s) => ({ team: s.team, from: s.from, to: s.to, rings: Array.isArray(s.rings) ? s.rings.filter(Number.isFinite) : [] }));
    if (!stints.length) return;
    out[k] = {
      stints,
      confidence: v.confidence && CONFIDENCE.has(v.confidence) ? v.confidence : 'likely',
      evidence: typeof v.evidence === 'string' ? v.evidence : '',
      approx: v.approx === true || undefined,
      preLeagueRings: typeof v.preLeagueRings === 'number' ? v.preLeagueRings : undefined,
      alternatives: Array.isArray(v.alternatives) ? v.alternatives : undefined,
    };
  });
  return out;
};

const toIndexed = (raw: Partial<PlayerExtras>): IndexedExtras => ({
  realNflCareer: reindex<RealNflCareer>(raw.realNflCareer),
  cards: reindex<PlayerCardExtras>(raw.cards),
  formerNames: reindex<string>(raw.formerNames),
  family: reindexWithName(raw.family),
  franchises: reindex<string[]>(raw.franchises),
  stints: normalizeStints(raw.stints),
  signatureTeams: Object.fromEntries(Object.entries(reindex<unknown>(raw.signatureTeams)).filter((e): e is [string, string] => typeof e[1] === 'string')),
});

const EMPTY_INDEXED = toIndexed(EMPTY);

let cache: IndexedExtras | null = null;
let inflight: Promise<IndexedExtras> | null = null;

/** Fetches the extras file once per session. Missing file (404) or bad JSON resolves to empty extras. */
export const loadPlayerExtras = (): Promise<IndexedExtras> => {
  if (cache) return Promise.resolve(cache);
  if (!inflight) {
    const url = `${import.meta.env.BASE_URL}data/player-extras.json`;
    inflight = fetch(url)
      .then((res) => (res.ok ? (res.json() as Promise<Partial<PlayerExtras>>) : EMPTY))
      .catch(() => EMPTY)
      .then((raw) => {
        cache = toIndexed(raw ?? EMPTY);
        return cache;
      });
  }
  return inflight;
};

/** React hook: empty extras until loaded, then the indexed file contents. */
export const usePlayerExtras = (): IndexedExtras => {
  const [extras, setExtras] = useState<IndexedExtras>(cache ?? EMPTY_INDEXED);
  useEffect(() => {
    if (cache) return;
    let alive = true;
    loadPlayerExtras().then((e) => alive && setExtras(e));
    return () => {
      alive = false;
    };
  }, []);
  return extras;
};

/** A player's reconstructed stints, or undefined when none are on file. */
export const getStints = (extras: IndexedExtras, playerName: string): PlayerStints | undefined => extras.stints[normalizeName(playerName)];

/**
 * The team a player's card and banners wear: where he was best known (signatureTeams), else his current team.
 * Only for identity (jersey, helmet, colours, logo); stats, rosters and team filters keep `player.team`.
 */
export const signatureTeamOf = (extras: IndexedExtras, player: { name: string; team?: string; isRealLegend?: boolean }): string =>
  (!player.isRealLegend && extras.signatureTeams[normalizeName(player.name)]) || player.team || '';

/** The player dressed in his signature team (same object when it already matches), for card and banner art. */
export const withSignatureTeam = <P extends { name: string; team?: string; isRealLegend?: boolean }>(extras: IndexedExtras, player: P): P => {
  const team = signatureTeamOf(extras, player);
  return team === (player.team ?? '') ? player : { ...player, team };
};

export interface FamilyTie {
  /** Relation text as shown, e.g. "Son of" or "Family" */
  label: string;
  /** The other player's name */
  name: string;
}

/**
 * Family ties for a player: their own entry ("son of X" -> Son of X) plus reverse links from players
 * who list them ("Y: son of <player>" -> Y, son).
 */
export const getFamilyTies = (extras: IndexedExtras, playerName: string): FamilyTie[] => {
  const me = normalizeName(playerName);
  const ties: FamilyTie[] = [];
  const parse = (text: string) => {
    const m = text.match(/^\s*(.+?)\s+of\s+(.+?)\s*$/i);
    return m ? { relation: m[1], other: m[2] } : null;
  };
  const own = extras.family[me];
  if (own) {
    const p = parse(own.value);
    if (p) ties.push({ label: `${p.relation[0].toUpperCase()}${p.relation.slice(1)} of`, name: p.other });
  }
  Object.entries(extras.family).forEach(([key, { name, value }]) => {
    if (key === me) return;
    const p = parse(value);
    if (p && normalizeName(p.other) === me) ties.push({ label: `Family (${p.relation.toLowerCase()})`, name });
  });
  return ties;
};
