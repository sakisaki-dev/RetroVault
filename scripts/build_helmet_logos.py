#!/usr/bin/env python3
"""Pixel-art helmet logos for the Retro Bowl sprite (dev tool, needs network + Pillow; output is committed).

Downloads each club's logo (the same ESPN CDN images the site uses for TeamLogo), crops it, fits it into a
LOGO_W × LOGO_H pixel box on the sprite's fine grid, thresholds the alpha and quantizes it to at most 3 colours.
Writes src/components/collection/art/helmetLogos.ts: { teamId: { rows: ["..1122..", ...], colors: ["#hex", ...] } }.
Teams whose helmet has a shell design instead of a logo decal (Bengals stripes, Rams horn, Eagles wings, Browns
plain) are drawn by hand in helmets.ts and skipped here.

Usage: python3 scripts/build_helmet_logos.py
"""
import io
import json
import urllib.request
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "components" / "collection" / "art" / "helmetLogos.ts"
LOGO_W, LOGO_H = 14, 12
TEAMS = {
    "bills": "buf", "dolphins": "mia", "patriots": "ne", "jets": "nyj", "ravens": "bal", "steelers": "pit",
    "texans": "hou", "colts": "ind", "jaguars": "jax", "titans": "ten", "broncos": "den", "chiefs": "kc",
    "raiders": "lv", "chargers": "lac", "cowboys": "dal", "giants": "nyg", "commanders": "wsh", "bears": "chi",
    "lions": "det", "packers": "gb", "vikings": "min", "falcons": "atl", "panthers": "car", "saints": "no",
    "buccaneers": "tb", "cardinals": "ari", "49ers": "sf", "seahawks": "sea",
}
SKIP = {"bengals", "rams", "eagles", "browns"}


def pixelate(img: Image.Image) -> dict:
    img = img.convert("RGBA")
    bbox = img.getchannel("A").point(lambda a: 255 if a > 40 else 0).getbbox()
    img = img.crop(bbox)
    scale = min(LOGO_W / img.width, LOGO_H / img.height)
    w, h = max(1, round(img.width * scale)), max(1, round(img.height * scale))
    small = img.resize((w, h), Image.Resampling.BOX)
    canvas = Image.new("RGBA", (LOGO_W, LOGO_H), (0, 0, 0, 0))
    canvas.paste(small, ((LOGO_W - w) // 2, (LOGO_H - h) // 2))
    opaque = [(x, y) for y in range(LOGO_H) for x in range(LOGO_W) if canvas.getpixel((x, y))[3] >= 128]
    rgb = Image.new("RGB", (len(opaque), 1))
    for i, (x, y) in enumerate(opaque):
        rgb.putpixel((i, 0), canvas.getpixel((x, y))[:3])
    q = rgb.quantize(colors=3, method=Image.Quantize.MEDIANCUT)
    pal = q.getpalette()[: 3 * 3]
    used = sorted({q.getpixel((i, 0)) for i in range(len(opaque))})
    remap = {c: n for n, c in enumerate(used)}
    rows = [["."] * LOGO_W for _ in range(LOGO_H)]
    for i, (x, y) in enumerate(opaque):
        rows[y][x] = str(remap[q.getpixel((i, 0))] + 1)
    colors = ["#%02x%02x%02x" % tuple(pal[c * 3 : c * 3 + 3]) for c in used]
    return {"rows": ["".join(r) for r in rows], "colors": colors}


def main():
    out = {}
    for team, code in TEAMS.items():
        if team in SKIP:
            continue
        url = f"https://a.espncdn.com/i/teamlogos/nfl/500/{code}.png"
        data = urllib.request.urlopen(url, timeout=30).read()
        out[team] = pixelate(Image.open(io.BytesIO(data)))
    head = ("// Generated by scripts/build_helmet_logos.py (do not hand-edit): pixel-art helmet logos on the sprite's fine grid.\n"
            "export const HELMET_LOGOS: Record<string, { rows: string[]; colors: string[] }> = ")
    OUT.write_text(head + json.dumps(out, indent=1) + ";\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(out)} logos at {LOGO_W}×{LOGO_H}")


if __name__ == "__main__":
    main()
