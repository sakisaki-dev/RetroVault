#!/usr/bin/env python3
"""Build public/data/league/content.json from data/y80. Run from the repo root (npm run rebuild runs it).

Everything here is generated by rules over the data, so it updates itself when the data changes:

* eras        runs of the owner's coaching stints (coach.json), split at long title droughts and merged when a
              stint won fewer than 3 titles; named "<Team> dynasty" (5+ titles), "<Team> run" (3-4) or
              "<Team> years"; key players = best Career Legacy whose stints (stints.json) overlap the era's clubs
* storylines  the Super Bowl ledger, era reports, rivalries, lineages, snubs, outsiders, record chases, iron men,
              one-team legends, plus the owner's own journal notes (data/y80/journal.json, quoted verbatim)
* rivalries   the franchises the owner met most in Super Bowls, with the W-L record and any owner notes
* lineages    family ties (screenshot_extras.json) and the quarterback succession on the owner's clubs
* hofClasses  who first crossed Career Legacy 7000 at each market snapshot (data/y80/market_history.json)
* playerNotes era (derived) and tag: owner tag + family / former name + league records and rate bests
* edition     the per-update seed: number of applied uploads (data/y80/mutations_log.json), the last one's id and
              the season, hashed (FNV-1a). The site's rotating picks (featured players, hero, headline order, featured
              storylines, pack shelf accent) key off it (src/utils/edition.ts), so each update looks fresh while a
              rebuild of the same data stays byte-identical. Player identity (looks, card art, poses) never uses it.

Career Legacy and OVR come from the latest market snapshot, which `npm run market` computes with the site's own
formulas just before this script runs. Speeches (data/y80/speeches.json) are the only authored text.
"""
