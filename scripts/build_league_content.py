def snapshot_season(s) -> str | None:
    if s.get("season"):
        return s["season"]
    m = re.match(r"(Y\d+) · ", s.get("label", ""))
    return m.group(1) if m else None


def hof_classes():
    if not MARKET:
        return []
    current = {k for k, v in MARKET[-1]["players"].items() if v.get("legacy", 0) >= HOF_THRESHOLD}
    seen: set[str] = set()
    classes: list[dict] = []
    for i, s in enumerate(MARKET):
        crossed = sorted((k for k, v in s["players"].items() if v.get("legacy", 0) >= HOF_THRESHOLD and k not in seen),
                         key=lambda k: (-MARKET[-1]["players"].get(k, {}).get("legacy", 0), k))
        seen.update(crossed)
        keys = [k for k in crossed if k in current]
        if not keys:
            continue
        label = "Inaugural class" if i == 0 else (snapshot_season(s) or s["label"])
        if classes and classes[-1]["label"] == label:
            classes[-1]["keys"] += keys
        else:
            classes.append({"label": label, "keys": keys, "snapshot": s["id"]})
    return classes


