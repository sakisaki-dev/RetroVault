def league_marks() -> dict[str, list[dict]]:
    """{name: [{label, value, tied, runner}]} for every career mark he holds (league players only)."""
    out: dict[str, list[dict]] = {}
    for label, poss, get in CAREER_MARKS:
        pool = [p for p in LEAGUE if poss is None or p["pos"] in poss]
        vals = sorted(((get(p), p["n"]) for p in pool), key=lambda v: (-v[0], v[1]))
        if not vals or vals[0][0] <= 0:
            continue
        top = vals[0][0]
        holders = [n for v, n in vals if v == top]
        runner = next(((v, n) for v, n in vals if v < top), None)
        for n in holders:
            out.setdefault(n, []).append({"label": label, "value": top, "tied": len(holders) > 1, "runner": runner})
    return out


MARKS = league_marks()


def rate_bests() -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for label, pos, num, den, minimum, min_label in RATE_BESTS:
        # QB TD:INT minimum is on attempts, not interceptions
        base = "att" if pos == "QB" else den
        pool = [p for p in LEAGUE if p["pos"] == pos and g(p, base) >= minimum and g(p, den) > 0]
        if len(pool) < 3:
            continue
        best = sorted(pool, key=lambda p: (-g(p, num) / g(p, den), p["n"]))[0]
        out.setdefault(best["n"], []).append(f"{label} (min {fmt(minimum)} {min_label})")
    return out


RATES = rate_bests()


def relation_tags(name: str) -> list[str]:
    tags = []
    for who, rel in sorted(EXTRAS.get("family", {}).items()):
        m = re.match(r"(\w+) of (.+)$", rel)
        if not m:
            continue
        kind, other = m.groups()
        if who == name:
            tags.append(f"{kind.capitalize()} of {other}")
        elif other == name:
            back = {"son": "Father", "father": "Son", "brother": "Brother", "daughter": "Parent"}.get(kind, "Family")
            tags.append(f"{back} of {who}")
    for old, new in sorted(EXTRAS.get("name_changes", {}).items()):
        if new == name:
            tags.append(f"Formerly {old}")
    return tags


def generated_tag(name: str) -> str | None:
    marks = [m for m in MARKS.get(name, []) if m["label"] not in ("rings", "games played") or not m["tied"]]
    solo = [m["label"] for m in marks if not m["tied"]]
    tied = [m["label"] for m in marks if m["tied"]]
    if solo:
        return ("League record: " if len(solo) == 1 else "League records: ") + join(solo[:3])
    if RATES.get(name):
        return RATES[name][0]
    if tied:
        return f"Shares the league record: {join(tied[:2])}"
    return None


def player_tag(name: str) -> str | None:
    parts = [F.TAGS.get(name), *relation_tags(name), generated_tag(name)]
    parts = [p for p in parts if p]
    return " · ".join(parts[:3]) or None


