def record_chases():
    out = []
    for label, poss, get in CAREER_MARKS:
        if label in ("rings", "MVPs", "Super Bowl MVPs", "games played") or "awards" in label:
            continue
        pool = [p for p in LEAGUE if poss is None or p["pos"] in poss]
        vals = sorted(pool, key=lambda p: (-get(p), p["n"]))
        if len(vals) < 2 or get(vals[0]) <= 0:
            continue
        holder = vals[0]
        chaser = next((p for p in vals[1:] if is_status_active(p["n"]) and get(p) < get(holder)), None)
        if not chaser:
            continue
        share = get(chaser) / get(holder)
        if share >= 0.6:
            out.append((share, label, holder, chaser, get))
    out.sort(key=lambda x: (-x[0], x[1]))
    return out[:4]


