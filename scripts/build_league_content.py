def era_of_year(eras, y):
    return next((e["name"] for e in eras if e["startYear"] <= y <= e["endYear"]), None)


def journal_for(team: str | None = None, player: str | None = None) -> list[dict]:
    return [n for n in JOURNAL if (team and team in n.get("teams", [])) or (player and player in n.get("players", []))]


def build_rivalries(eras):
    games = your_games()
    by_opp: dict[str, list[dict]] = {}
    for gm in games:
        if gm["opponent"] and gm["opponent"] != "None":
            by_opp.setdefault(gm["opponent"], []).append(gm)
    ranked = sorted(by_opp.items(), key=lambda kv: (-len(kv[1]), -sum(not x["won"] for x in kv[1]), -kv[1][-1]["year"], kv[0]))
    out = []
    for opp, gs in ranked:
        # only the owner's rivalry / dispute notes make (or annotate) a rivalry; a roster note that tags a club does not
        noted = [n for n in journal_for(team=opp) if n.get("kind") in ("rivalry", "dispute")]
        if len(gs) < 2 and not noted:
            continue
        if len(out) >= 4 and not noted:
            continue
        w = sum(x["won"] for x in gs)
        l = len(gs) - w
        meet_years = [x["year"] for x in gs]
        # their star: the best Career Legacy player on their side in those seasons
        star, star_n = None, 0
        for p in sorted(LEAGUE, key=lambda p: (-legacy(p["n"]), p["n"])):
            n = sum(1 for x in dated_stints(p["n"]) for y in meet_years if x["team"] == opp and x["from"] <= y <= x["to"])
            if n * 2 >= len(gs):  # on their side for at least half the meetings
                star, star_n = p, n
                break
        record = (f"won all {len(gs)}" if not l else f"lost all {len(gs)}" if not w else f"went {w}–{l}")
        lines = [f"{x['roman']} (Y{x['year']}) {'W' if x['won'] else 'L'} {x['yourScore']}" for x in gs]
        summary = f"You met the {opp} in {plural(len(gs), 'Super Bowl')} and {record}: {join(lines)}."
        if star:
            both = "every one" if star_n == len(gs) else f"{star_n} of them"
            summary += (f" {star['n']} ({star['pos']}, Career Legacy {fmt(legacy(star['n']))}) was on their side for "
                        f"{both}." if len(gs) > 1 else f" {star['n']} ({star['pos']}) was on their side.")
        h = SCHEDULE["headToHead"].get(opp)
        if h:
            summary += (f" In the weekly scores you went {h['record']} against them: "
                        f"{join([m['season'] + ' ' + m['round'].lower() + ' ' + m['result'] + ' ' + str(m['for']) + '-' + str(m['against']) for m in h['meetings']])}.")
        eras_hit: dict[str, int] = {}
        for y in meet_years:
            e = era_of_year(eras, y)
            if e:
                eras_hit[e] = eras_hit.get(e, 0) + 1
        era = sorted(eras_hit.items(), key=lambda kv: (-kv[1], -[e["name"] for e in eras].index(kv[0])))[0][0] if eras_hit else None
        out.append({
            "id": f"rival-{slug(opp)}",
            "rival": star["n"] if star else opp,
            "team": opp,
            **({"era": era} if era else {}),
            "summary": summary,
            "record": {"won": w, "lost": l},
            "meetings": [{"roman": x["roman"], "year": x["year"], "score": x["yourScore"], "result": "won" if x["won"] else "lost",
                          "yourTeam": x["team"], "opponent": opp} for x in gs],
            **({"ownerNotes": [note_ref(n) for n in noted]} if noted else {}),
            **({"games": SCHEDULE["headToHead"][opp]} if opp in SCHEDULE["headToHead"] else {}),
        })
    # Weekly scores: a club the coach's teams met at least twice in games and never had the better of (wins at most
    # losses plus ties) is a rivalry too, even with no Super Bowl between them
    # A lasting rivalry (rivalry_status: a home-and-away series that keeps going) is one too, whatever the record
    have = {r["team"] for r in out}
    for opp, h in SCHEDULE["headToHead"].items():
        if opp in have or ((h["games"] < 2 or h["w"] > h["l"] + h["t"]) and not rivalry_status(h)):
            continue
        seasons = sorted({m["season"] for m in h["meetings"]}, key=lambda y: int(y.lstrip("Y")))
        lines = [f"{m['season']} {m['round'].lower()} {m['result']} {m['for']}-{m['against']}" for m in h["meetings"]]
        out.append({
            "id": f"rival-{slug(opp)}",
            "rival": opp,
            "team": opp,
            **({"era": era_of_year(eras, int(seasons[-1].lstrip("Y")))} if era_of_year(eras, int(seasons[-1].lstrip("Y"))) else {}),
            "summary": f"You met the {opp} {plural(h['games'], 'time')} in {join(seasons)} and went {h['record']}: {join(lines)}.",
            "record": {"won": h["w"], "lost": h["l"], **({"tied": h["t"]} if h["t"] else {})},
            "meetings": [],
            "games": h,
            "source": "weekly scores",
        })
    # Each rivalry with a rivalry file (build_rivalry_files) says so: lasting, or lapsed (Past rivalries)
    for r in out:
        h = SCHEDULE["headToHead"].get(r["team"])
        st = rivalry_status(h) if h and r["team"] in TEAMS_JSON else None
        if st:
            r["file"] = f"rivalry-{slug(r['team'])}"
            r["lasting"] = st == "lasting"
    return out


def note_ref(n):
    return {k: n[k] for k in ("id", "text", "season", "kind", "players", "teams") if n.get(k) is not None}


