def ordinal(n: int) -> str:
    if n == 1:
        return "first"
    return f"{n}{'th' if 10 <= n % 100 <= 20 else {1: 'st', 2: 'nd', 3: 'rd'}.get(n % 10, 'th')}"


def season_num(s) -> int:
    return int(re.sub(r"\D", "", snapshot_season(s) or "0") or 0)


def bundle_mutations(entries: list[dict]) -> list[dict]:
    out = []
    for e in entries:
        if not e.get("changed"):
            continue  # a bundle that changed nothing (the backfilled initial record) has no news
        path = ROOT / e.get("dir", f"data/uploads/{e['id']}") / "manifest.json"
        if path.exists():
            out += json.loads(path.read_text()).get("mutations", [])
    return out


def teams_before(bundle_id: str) -> dict[str, str]:
    """Each player's club as the applied bundles left it just before `bundle_id` (player.set team, then
    owner team facts in order). Players never given a club through a bundle are absent."""
    log_path = SRC / "mutations_log.json"
    applied = json.loads(log_path.read_text()).get("applied", []) if log_path.exists() else []
    teams: dict[str, str] = {}
    for e in applied:
        if e["id"] == bundle_id:
            break
        path = ROOT / e.get("dir", f"data/uploads/{e['id']}") / "manifest.json"
        if not path.exists():
            continue
        for m in json.loads(path.read_text()).get("mutations", []):
            if m.get("op") == "player.set" and isinstance(m.get("value"), dict) and m["value"].get("team"):
                teams[m["target"].split(":", 1)[-1]] = m["value"]["team"]
            mt = re.match(r"players/(.+)/team$", str(m.get("target", "")))
            if m.get("op") == "fact.set" and mt and isinstance(m.get("value"), str):
                teams[mt.group(1)] = m["value"]
    return teams


def pair_headlines(prev: dict | None, cur: dict | None, bundles: list[dict]) -> list[dict]:
    """Headlines for one update: the snapshot pair's diff (prev -> cur) plus the bundles' own facts."""
    out: list[dict] = []

    def add(kind, text, weight, players=(), teams=()):
        out.append({"kind": kind, "text": text, "players": list(players), "teams": list(teams), "weight": int(weight)})

    muts = bundle_mutations(bundles)
    a = prev["players"] if prev else {}
    b = cur["players"] if cur else {}

    # Super Bowls: seasons the pair rolled over, plus superbowl.set mutations
    years = set(range(season_num(prev) + 1, season_num(cur) + 1)) if prev and cur else set()
    years |= {int(m["target"].lstrip("Y")) for m in muts if m["op"] == "superbowl.set" and m["target"].lstrip("Y").isdigit()}
    for y in sorted(years):
        sb = SB_BY_YEAR.get(y)
        if not sb or not sb.get("winner"):
            continue
        if sb["your_result"] == "won":
            add("superbowl", f"{sb['your_team']} win Super Bowl {sb['roman']}", 100, teams=[sb["your_team"], sb["loser"]])
        elif sb["your_result"] == "lost":
            add("superbowl", f"{sb['your_team']} fall to the {sb['winner']} in Super Bowl {sb['roman']}", 88,
                teams=[sb["your_team"], sb["winner"]])
        else:
            add("superbowl", f"{sb['winner']} win Super Bowl {sb['roman']}", 60, teams=[sb["winner"]])

    # Records: record.set mutations, plus marks dated in a rolled-over season
    rec_names = {m["target"] for m in muts if m["op"] == "record.set"}
    for r in RECORDS:
        y = int(r["year"].lstrip("Y")) if r["year"].lstrip("Y").isdigit() else None
        if r["record"] in rec_names or (y in years):
            names = [n for n in board_holder_names(r["holder"]) if n in BY_NAME]
            add("record", f"Record broken: {r['record'].lower()}, {r['mark']} ({join([short(n) for n in names]) or r['holder']}, {r['year']})",
                85, players=names)

    # Trades: owner-stated team facts that move a player off a known club. A first placement (a new player
    # or one listed as UNK/CUR), a fact restating the same club, or a correction whose reason doesn't say
    # "trade" is not a trade.
    before = teams_before(bundles[0]["id"]) if bundles else {}
    for m in muts:
        mt = re.match(r"players/(.+)/team$", m["target"])
        if m["op"] == "fact.set" and mt and isinstance(m["value"], str) and m["value"] not in ("UNK", "CUR"):
            was = before.get(mt.group(1))
            if was in ("UNK", "CUR") or was == m["value"] or not re.search(r"\btrad", m.get("reason", ""), re.I):
                continue  # first placement, same club, or a correction the owner didn't describe as a trade
            add("trade", f"Traded: {short(mt.group(1))} to the {m['value']}", 80, players=[mt.group(1)], teams=[m["value"]])

    if prev and cur:
        name_of = {k: k.split(":", 1)[1] for k in b}
        # New Hall of Famers: crossed Career Legacy 7000 in this pair and still in
        for k in sorted(b, key=lambda k: (-b[k]["legacy"], k)):
            if b[k]["legacy"] >= HOF_THRESHOLD and a.get(k, {}).get("legacy", 0) < HOF_THRESHOLD \
                    and LATEST.get(k, {}).get("legacy", 0) >= HOF_THRESHOLD:
                add("hof", f"New Hall of Famer: {name_of[k]}", 90, players=[name_of[k]])
        # New players
        new = sorted((k for k in b if k not in a), key=lambda k: (-b[k]["legacy"], k))
        for k in new[:4]:
            add("new-player", f"New player: {name_of[k]} ({k.split(':')[0]}, Career Legacy {fmt(b[k]['legacy'])})",
                70 + min(8, b[k]["legacy"] // 1500), players=[name_of[k]])
        if len(new) > 4:
            add("new-player", f"{plural(len(new) - 4, 'more new player')} in the league", 66, players=[name_of[k] for k in new[4:]])
        # Milestones and awards (players in both snapshots with career totals)
        tops: dict[tuple, int] = {}
        for key, poss, label, step in MILESTONES:
            tops[(key, label)] = max((v.get("s", {}).get(key, 0) for k, v in b.items() if poss is None or k.split(":")[0] in poss), default=0)
        for k in sorted(set(a) & set(b)):
            sa, sb_ = a[k].get("s"), b[k].get("s")
            if not sa or not sb_:
                continue
            pos, n = k.split(":", 1)
            for key, poss, label, step in MILESTONES:
                if poss is not None and pos not in poss:
                    continue
                lo, hi = sa.get(key, 0), sb_.get(key, 0)
                th = hi // step * step
                if th > lo and th >= step:
                    top = tops[(key, label)] or 1
                    text = f"{short(n)} plays his {fmt(th)}th game" if key == "g" else f"{short(n)} passes {fmt(th)} {label}"
                    add("milestone", text, 55 + round(25 * min(1, th / top)), players=[n])
            for key, label, w in AWARDS:
                lo, hi = sa.get(key, 0), sb_.get(key, 0)
                if hi > lo:
                    add("award", f"{short(n)} wins his {ordinal(hi)} {label}", w + min(10, hi), players=[n])
        # Skill grade families
        for k in sorted(set(a) & set(b)):
            ga, gb = (a[k].get("grade") or "")[:1], (b[k].get("grade") or "")[:1]
            if not ga or not gb or ga == gb:
                continue
            n = name_of[k]
            up = GRADE_ORDER.index(gb) < GRADE_ORDER.index(ga)
            if gb == "S":
                add("grade", f"{short(n)} enters S tier", 68, players=[n])
            elif ga == "S":
                add("grade", f"{short(n)} drops out of S tier", 50, players=[n])
            elif up:
                add("grade", f"{short(n)} climbs to an {gb} grade" if gb in "AF" else f"{short(n)} climbs to a {gb} grade", 48, players=[n])
        # Market: top risers and fallers by base-card value
        moves = []
        for k in set(a) & set(b):
            va, vb = a[k].get("value", 0), b[k].get("value", 0)
            if va >= MARKET_MIN_VALUE and va and abs(vb - va) / va >= MARKET_MIN_MOVE:
                moves.append(((vb - va) / va, k))
        risers = sorted((m for m in moves if m[0] > 0), key=lambda m: (-m[0], m[1]))[:3]
        fallers = sorted((m for m in moves if m[0] < 0), key=lambda m: (m[0], m[1]))[:2]
        for pct, k in risers + fallers:
            n = name_of[k]
            sign = "+" if pct > 0 else "−"
            add("market", f"Market: {short(n)} {sign}{abs(round(pct * 100))}%", 40 + min(15, round(abs(pct) * 30)), players=[n])
    return out


def chase_headlines() -> list[dict]:
    """Standing news: active players closing on a career league record (the same rule as the Record Chase stories)."""
    out = []
    for share, label, holder, chaser, get in record_chases():
        if share < 0.85:
            continue
        gap = get(holder) - get(chaser)
        unit = label.replace("career ", "")
        out.append({"kind": "chase", "text": f"{short(chaser['n'])} is {fmt(gap)} {unit} from the all-time mark",
                    "players": [chaser["n"], holder["n"]], "teams": [], "weight": 30 + round(share * 10)})
    return out


def build_headlines() -> tuple[list[dict], dict]:
    """The latest update's headlines; when it changed nothing worth a headline, the most recent update that did
    (walking back through the snapshot pairs), marked "Last update"."""
    log_path = SRC / "mutations_log.json"
    applied = json.loads(log_path.read_text()).get("applied", []) if log_path.exists() else []
    ids = [e["id"] for e in applied]

    def bundles_for(i: int) -> list[dict]:
        """Bundles applied between snapshot i-1 and snapshot i (needs both to carry `upload`)."""
        up = MARKET[i].get("upload")
        if up not in ids:
            return []
        prev_up = MARKET[i - 1].get("upload") if i > 0 else None
        start = ids.index(prev_up) + 1 if prev_up in ids else ids.index(up)
        return applied[start:ids.index(up) + 1]

    def ranked(items: list[dict]) -> list[dict]:
        """By weight; duplicates dropped and at most PER_PLAYER headlines about any one player, so one big
        update to a single card doesn't fill the list."""
        seen, per, out = set(), {}, []
        for h in sorted(items, key=lambda h: (-h["weight"], KIND_ORDER.index(h["kind"]), h["text"])):
            solo = h["players"][0] if len(h["players"]) == 1 else None
            if h["text"] in seen or (solo and per.get(solo, 0) >= PER_PLAYER):
                continue
            seen.add(h["text"])
            if solo:
                per[solo] = per.get(solo, 0) + 1
            out.append(h)
        return out

    info: dict = {}
    news: list[dict] = []
    last = applied[-1] if applied else None
    if last and len(MARKET) >= 2 and MARKET[-1].get("upload") == last["id"]:
        news = pair_headlines(MARKET[-2], MARKET[-1], bundles_for(len(MARKET) - 1))
        info = {"scope": "This update", "upload": last["id"], "since": MARKET[-2]["label"], "label": MARKET[-1]["label"]}
    elif last:
        news = pair_headlines(None, None, [last])
        info = {"scope": "This update", "upload": last["id"]}
    if not news:
        for i in range(len(MARKET) - 1, 0, -1):
            news = pair_headlines(MARKET[i - 1], MARKET[i], bundles_for(i))
            if news:
                info = {"scope": "Last update", "since": MARKET[i - 1]["label"], "label": MARKET[i]["label"],
                        **({"upload": MARKET[i]["upload"]} if MARKET[i].get("upload") else {})}
                break
    news = ranked(news)[:MAX_HEADLINES - 2] + ranked(chase_headlines())[:2]
    return news, info


