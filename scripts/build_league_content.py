def coaching_stints() -> list[dict]:
    out: list[dict] = []
    for s in SEASONS:
        if out and out[-1]["teams"][-1] == s["team"] and out[-1]["end"] == s["year"] - 1:
            out[-1]["end"] = s["year"]
        else:
            out.append({"start": s["year"], "end": s["year"], "teams": [s["team"]]})
    return out


def titles_in(a: int, b: int) -> list[int]:
    return [y for y in WON if a <= y <= b]


def split_droughts(seg: dict, gap: int = 3) -> list[dict]:
    """Split a stint at a run of `gap`+ title-less seasons that has titles on both sides."""
    ts = titles_in(seg["start"], seg["end"])
    for a, b in zip(ts, ts[1:]):
        if b - a - 1 >= gap:
            left = {**seg, "end": a + (b - a - 1) // 2}
            right = {**seg, "start": left["end"] + 1}
            return split_droughts(left, gap) + split_droughts(right, gap)
    return [seg]


def derive_eras() -> list[dict]:
    segs = [s for st in coaching_stints() for s in split_droughts(st)]
    merged: list[dict] = []
    pending = None  # a thin first segment waits to join the next one
    for i, s in enumerate(segs):
        s = {**s, "teams": list(s["teams"])}
        if pending:
            s = {"start": pending["start"], "end": s["end"], "teams": pending["teams"] + [t for t in s["teams"] if t not in pending["teams"]]}
            pending = None
        thin = len(titles_in(s["start"], s["end"])) < 3
        is_last = i == len(segs) - 1
        if thin and not is_last:
            if merged:
                m = merged[-1]
                m["end"] = s["end"]
                m["teams"] += [t for t in s["teams"] if t not in m["teams"]]
            else:
                pending = s
            continue
        merged.append(s)
    if pending:
        merged.append(pending)
    return merged


def lead_team(a: int, b: int, teams: list[str]) -> str:
    def key(t):
        n_titles = sum(1 for y in titles_in(a, b) if SB_BY_YEAR[y]["your_team"] == t)
        n_seasons = sum(1 for y in range(a, b + 1) if OWNER.get(y) == t)
        return (-n_titles, -n_seasons, teams.index(t))
    return sorted(teams, key=key)[0]


def roman_range(a: int, b: int) -> str | None:
    rs = [SB_BY_YEAR[y]["roman"] for y in range(a, b + 1) if y in SB_BY_YEAR]
    return f"{rs[0]}–{rs[-1]}" if len(rs) > 1 else (rs[0] if rs else None)


def sb_line(y: int) -> str:
    s = SB_BY_YEAR[y]
    return f"{s['roman']} (Y{y})"


def your_score(s) -> str:
    if not s.get("score"):
        return "score not recorded"
    a, _, b = s["score"].partition("-")
    return f"{a}–{b}" if s["your_result"] == "won" else f"{b}–{a}"


def era_record(a: int, b: int):
    rows = [s for s in SEASONS if a <= s["year"] <= b]
    w, l, t = (sum(r[k] for r in rows) for k in ("w", "l", "t"))
    best = sorted(rows, key=lambda r: (-(r["w"] + 0.5 * r["t"]) / max(1, r["w"] + r["l"] + r["t"]), -(r["finish"] == "Champions"), r["year"]))[0]
    return w, l, t, best


def build_eras():
    eras, names = [], {}
    for seg in derive_eras():
        a, b, teams = seg["start"], seg["end"], seg["teams"]
        ts = titles_in(a, b)
        lead = lead_team(a, b, teams)
        kind = "dynasty" if len(ts) >= 5 else "run" if len(ts) >= 3 else "years"
        name = f"{lead} {kind}"
        names[name] = names.get(name, 0) + 1
        if names[name] > 1:
            name += " " + "I" * names[name]
        span = range(a, b + 1)
        # key players: best Career Legacy among those who played for the owner's club in this window
        seasons_with = {}
        for p in LEAGUE:
            n = len(owner_overlap(p["n"], span))
            if n:
                seasons_with[p["n"]] = n
        key = sorted(seasons_with, key=lambda n: (-legacy(n), n))[:KEY_PLAYERS_PER_ERA]
        w, l, t, best = era_record(a, b)
        apps = [y for y in span if y in SB_BY_YEAR and SB_BY_YEAR[y]["your_result"] in ("won", "lost")]
        losses = [y for y in apps if SB_BY_YEAR[y]["your_result"] == "lost"]
        streak = longest_run(ts)
        # notes: computed facts only
        bits = [f"{plural(len(ts), 'title')} in {plural(b - a + 1, 'season')} ({year_runs(ts) or 'none'})"]
        if streak[0] >= 3:
            bits[0] += f", {streak[0]} straight from Y{streak[1]}"
        notes = [bits[0] + "."]
        rec = f"{w}–{l}" + (f"–{t}" if t else "")
        notes.append(f"{rec} in the regular season; best season Y{best['year']} ({best['w']}–{best['l']}"
                     + (f"–{best['t']}" if best["t"] else "") + f", {best['finish']}).")
        if len(apps):
            notes.append(f"{len(apps) - len(losses)}–{len(losses)} in Super Bowls.")
        if key:
            mvp = sum(g(BY_NAME[n], "mvp") for n in key)
            sbmvp = sum(g(BY_NAME[n], "sbmvp") for n in key)
            notes.append(f"Its key players own {plural(mvp, 'MVP')} and {plural(sbmvp, 'Super Bowl MVP')} between them.")
        marks = [r for r in BOARD if a <= r["y"] <= b and any(n in BY_NAME for n in r["names"])]
        if marks:
            notes.append(f"{plural(len(marks), 'record-board mark')} set.")
        history = []
        for team in teams:
            ys = [y for y in span if OWNER.get(y) == team]
            rows = [s for s in SEASONS if s["year"] in ys]
            tw, tl, tt = (sum(r[k] for r in rows) for k in ("w", "l", "t"))
            history.append(f"- **{team}** {year_runs(ys)}: {tw}–{tl}{f'–{tt}' if tt else ''}, "
                           f"{plural(len([y for y in ts if SB_BY_YEAR[y]['your_team'] == team]), 'title')}")
        for y in losses:
            s = SB_BY_YEAR[y]
            history.append(f"- **Lost** {sb_line(y)} to the {s['winner']}, {your_score(s)}")
        for r in marks:
            who = join([n for n in r["names"]])
            history.append(f"- **Record:** {r['record'].lower()}, {r['mark']} ({who}, Y{r['y']})")
        lost_to: dict[str, list[int]] = {}
        for y in losses:
            lost_to.setdefault(SB_BY_YEAR[y]["winner"], []).append(y)
        rival = None
        if lost_to:
            opp, ys = sorted(lost_to.items(), key=lambda kv: (-len(kv[1]), kv[1][0]))[0]
            rival = f"The {opp} beat you in {join([sb_line(y) for y in ys])}"
        eras.append({
            "id": slug(name), "name": name, "startYear": a, "endYear": b,
            "superBowlRange": roman_range(a, b), "yourTeams": teams, "keyPlayers": key,
            **({"rival": rival} if rival else {}),
            "notes": " ".join(notes), "history": "\n".join(history),
        })
    return eras


def player_era(name: str, eras: list[dict]) -> str | None:
    """The era he spent most seasons with the owner's club in; else the era his dated career overlaps most."""
    best, best_n = None, 0
    for e in eras:
        n = len(owner_overlap(name, range(e["startYear"], e["endYear"] + 1)))
        if n > best_n:
            best, best_n = e["name"], n
    if best:
        return best
    years = {y for x in dated_stints(name) for y in range(x["from"], x["to"] + 1)}
    for e in eras:
        n = len(years & set(range(e["startYear"], e["endYear"] + 1)))
        if n > best_n:
            best, best_n = e["name"], n
    return best


