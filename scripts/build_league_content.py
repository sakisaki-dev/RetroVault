def board_names() -> set[str]:
    return {n for r in RECORDS for n in board_holder_names(r["holder"])}


def tribute_candidates(rivalries: list[dict]) -> list[dict]:
    """The deterministic rule for who has enough material for a tribute: Career Legacy at the Hall of Fame bar or a
    Hall of Famer, AND at least TRIBUTE_MIN_REASONS of: two or more clubs or a trade on record (stints.json, an owner
    team_history or a career line that mentions a trade), a journal mention, a record (a club record-board mark or a
    league career mark), a rivalry (named as a rivalry's star), AWARD_KINDS_MIN of the five award kinds, an owner
    career line (`says`). Highest Career Legacy first."""
    board = board_names()
    rivals = {r["rival"] for r in rivalries}
    mentions: dict[str, int] = {}
    for n in JOURNAL:
        for x in n.get("players", []):
            mentions[x] = mentions.get(x, 0) + 1
    out = []
    for p in LEAGUE:
        n, key = p["n"], f'{p["pos"]}:{p["n"]}'
        hof = is_hall_of_famer(key)
        if legacy(n) < HOF_THRESHOLD and not hof:
            continue
        f = FACTS.get(n, {})
        says = (f.get("career") or {}).get("says") or ""
        clubs = {x["team"] for x in STINTS.get(n, {}).get("stints", [])}
        kinds = sum(1 for ks in AWARD_KINDS if any(g(p, k) > 0 for k in ks))
        reasons = [label for label, ok in (
            ("clubs", len(clubs) >= 2 or bool(f.get("team_history")) or bool(re.search(r"\btrad", says, re.I))),
            ("journal", mentions.get(n, 0) > 0),
            ("records", n in board or n in MARKS),
            ("rivalry", n in rivals),
            ("awards", kinds >= AWARD_KINDS_MIN),
            ("career", bool(says)),
        ) if ok]
        if len(reasons) >= TRIBUTE_MIN_REASONS:
            out.append({"key": key, "name": n, "careerLegacy": legacy(n), "hallOfFamer": hof, "reasons": reasons})
    return sorted(out, key=lambda c: (-c["careerLegacy"], c["key"]))


# One tribute per season (owner, 2026-11-14: "pick one per season based on relevance for that season or if there's no
# one notable pick from the list"). Each qualifying candidate (tribute_candidates) is scored by what happened to him in
# that season; the best score at or over TRIBUTE_NOTABLE is the season's pick, else the queue's head (the candidates
# with no tribute and no earlier pick, highest Career Legacy first). Ties: Career Legacy, then key. Nobody is picked
# twice, and a season whose bundles wrote a tribute keeps that tribute as its pick (so a later upload never re-picks a
# season already written).
TRIBUTE_SIGNALS = {  # kind -> weight; the order breaks ties for a pick's headline reason
    "hof": 3,       # voted into the Hall of Fame that season (its class)
    "retired": 3,   # his final season (games last rose in it) or retired by a status fact in that season's bundles
    "gauntlet": 3,  # completed the award set that season: a ring, MVP, OPOY/DPOY, Rookie of the Year, Super Bowl MVP
    "record": 2,    # a record-board mark dated that season or set by its bundles, or took a league career mark
    "award": 2,     # MVP 2; OPOY, DPOY and Super Bowl MVP 1 each (career deltas across the season's snapshot pair)
    "story": 2,     # the Season Story's lead names him first (2) or at all (1)
    "trade": 1,     # changed clubs that season (owner or roster/save team facts in its bundles)
}
TRIBUTE_NOTABLE = 3  # one big moment (Hall of Fame, final season, the Gauntlet) or two smaller ones
AWARD_WEIGHTS = {"mvp": ("MVP", 2), "opoy": ("Offensive Player of the Year", 1),
                 "dpoy": ("Defensive Player of the Year", 1), "sbmvp": ("Super Bowl MVP", 1)}


def season_bundles() -> dict[int, list[tuple[str, list[dict]]]]:
    """Applied bundles by season: a bundle belongs to the latest coach.season applied up to and including it (a
    season's import opens it; its follow-ups, retirements and written pieces stay with it). [(id, mutations)]."""
    log_path = SRC / "mutations_log.json"
    applied = json.loads(log_path.read_text()).get("applied", []) if log_path.exists() else []
    out: dict[int, list[tuple[str, list[dict]]]] = {}
    season = 0
    for e in applied:
        path = ROOT / e.get("dir", f"data/uploads/{e['id']}") / "manifest.json"
        muts = json.loads(path.read_text()).get("mutations", []) if path.exists() else []
        for m in muts:
            if m.get("op") == "coach.season" and str(m.get("target", "")).isdigit():
                season = max(season, int(m["target"]))
        if e.get("changed"):
            out.setdefault(season, []).append((e["id"], muts))
    return out


def _season_ends() -> dict[int, dict]:
    """Season -> its last market snapshot's players."""
    return {int(y.lstrip("Y")): s["players"] for y, s in _season_snaps()}


def tribute_signals(season: int, keys: set[str], ends: dict[int, dict], bundles: list[list[dict]],
                    teams_at: dict[str, str]) -> dict[str, list[dict]]:
    """POS:Name -> [{kind, weight, detail}] for what happened to each of `keys` in `season`."""
    out: dict[str, list[dict]] = {k: [] for k in keys}
    name_key = {k.partition(":")[2]: k for k in keys}
    seasons = sorted(ends)
    cur, prev = ends.get(season), ends.get(season - 1)
    muts = [m for ms in bundles for m in ms]

    def add(k, kind, weight, detail):
        if k in out:
            out[k].append({"kind": kind, "weight": weight, "detail": detail})

    def s(snap, k):
        return ((snap or {}).get(k) or {}).get("s") or {}

    def games_rose(k, y):
        a, b = ends.get(y - 1), ends.get(y)
        # a lone rise between the first two recorded seasons is the first import being corrected, not a season
        return bool(a and b and k in b and y - 1 != seasons[0] and (s(b, k).get("g") or 0) > (s(a, k).get("g") or 0))

    played = {k for k in keys if games_rose(k, season)}
    # Hall of Fame class of the season
    for k, m in hall_of_fame.members().items():
        if m.get("classSeason") == f"Y{season}":
            add(k, "hof", TRIBUTE_SIGNALS["hof"], f"voted into the Hall of Fame (class of Y{season})")
    # retired: his final season (retired now, games last rose this season) or a Retired status fact this season
    status_retired = {re.match(r"players/(.+)/status$", m["target"]).group(1) for m in muts
                      if m.get("op") == "fact.set" and re.match(r"players/(.+)/status$", str(m.get("target", "")))
                      and m.get("value") == "Retired"}
    for k in keys:
        n = k.partition(":")[2]
        final = k in played and not is_status_active(n) and not any(games_rose(k, y) for y in seasons if y > season)
        if final:
            add(k, "retired", TRIBUTE_SIGNALS["retired"], f"played his final season in Y{season}")
        elif n in status_retired:
            add(k, "retired", TRIBUTE_SIGNALS["retired"], f"retirement recorded in Y{season}")
    # records: board marks dated this season or set by its bundles, and league career marks taken this season
    rows = {m["target"]: m["value"] for m in muts
            if m.get("op") == "record.set" and "mark" in (m.get("value") or {}) and m["value"].get("holder")}
    rows.update({r["record"]: r for r in RECORDS if r["year"] == f"Y{season}"})
    rec: dict[str, list[str]] = {}
    for label, r in rows.items():
        for n in board_holder_names(r["holder"]):
            if n in name_key:
                rec.setdefault(name_key[n], []).append(f"{label} ({r['mark']})")
    if cur and prev:
        def top(snap, poss, get):
            vals = [(get({"pos": k.partition(":")[0], **(v.get("s") or {})}), k) for k, v in snap.items()
                    if poss is None or k.partition(":")[0] in poss]
            best = max((v for v, _ in vals), default=0)
            return best, {k for v, k in vals if v == best and v > 0}
        for label, poss, get in CAREER_MARKS:
            b_best, b_keys = top(cur, poss, get)
            a_best, a_keys = top(prev, poss, get)
            for k in sorted(b_keys - a_keys):
                if k in played:
                    rec.setdefault(k, []).append(f"took the league mark for {label}")
    for k, items in rec.items():
        add(k, "record", TRIBUTE_SIGNALS["record"], "; ".join(sorted(set(items))))
    # awards and the Gauntlet (only for a player who played the season, so a corrected career line is no award)
    for k in played:
        a, b = s(prev, k), s(cur, k)
        for f, (label, w) in AWARD_WEIGHTS.items():
            d = (b.get(f) or 0) - (a.get(f) or 0)
            if d > 0:
                add(k, "award", w * d, f"won {label}" + (f" x{d}" if d > 1 else ""))
        dfn = k.partition(":")[0] in DEFENSE
        roty = g(BY_NAME.get(k.partition(":")[2], {}), "roty")  # a rookie award: the snapshots don't carry it

        def full(x):
            return roty > 0 and all((x.get(f) or 0) > 0 for f in ("rings", "mvp", "dpoy" if dfn else "opoy", "sbmvp"))
        if full(b) and not full(a):
            add(k, "gauntlet", TRIBUTE_SIGNALS["gauntlet"], "completed the Gauntlet (every major award)")
    # traded or changed clubs: a team fact (owner, roster screen or save) moving him off a known club
    for m in muts:
        mt = re.match(r"players/(.+)/team$", str(m.get("target", "")))
        n = mt.group(1) if mt and m.get("op") == "fact.set" else None
        if m.get("op") == "player.set" and isinstance(m.get("value"), dict) and m["value"].get("team"):
            n = m["target"].split(":", 1)[-1]
            new = m["value"]["team"]
        else:
            new = m.get("value")
        if not n or not isinstance(new, str):
            continue
        was = teams_at.get(n)
        teams_at[n] = new
        if n in name_key and was not in (None, "UNK", "CUR", "FA") and new not in ("UNK", "CUR", "FA", was):
            add(name_key[n], "trade", TRIBUTE_SIGNALS["trade"], f"moved from the {was} to the {new}")
    # the Season Story's lead
    lead = next((a for a in STORIES.get(f"Y{season}", {}).get("articles", []) if a.get("kind") == "lead"), None)
    for i, n in enumerate((lead or {}).get("players", [])):
        if n in name_key:
            add(name_key[n], "story", 2 if i == 0 else 1, "led the Season Story" if i == 0 else "named in the Season Story's lead")
    return out


def tribute_plan(candidates: list[dict], first: int | None = None, last: int | None = None) -> list[dict]:
    """One pick per season from `first` (default: the first season whose bundles wrote a tribute, else the latest
    season) to `last` (default: the latest completed season), oldest first: [{season, player, reason, detail, score,
    signals, written}]. Seasons before `first` only advance the running team map."""
    by_season = season_bundles()
    written_in: dict[int, list[str]] = {}
    for y, bs in sorted(by_season.items()):
        for _, muts in bs:
            for m in muts:
                if m.get("op") == "tribute.set" and m["target"] in TRIBUTES and m["target"] not in sum(written_in.values(), []):
                    written_in.setdefault(y, []).append(m["target"])
    last = LAST if last is None else last
    first = first if first is not None else (min(written_in) if written_in else last)
    ends = _season_ends()
    legacy_of = {c["key"]: c["careerLegacy"] for c in candidates}
    keys = set(legacy_of)
    teams_at: dict[str, str] = {}
    plan, taken = [], set()
    for y in sorted(set(by_season) | set(range(first, last + 1))):
        if y > last:
            break
        sig = tribute_signals(y, keys, ends, [m for _, m in by_season.get(y, [])], teams_at)
        if y < first:
            continue
        score = {k: sum(x["weight"] for x in v) for k, v in sig.items()}
        locked = next((k for k in written_in.get(y, []) if k not in taken), None)
        if locked:
            pick = locked
        else:
            open_ = [k for k in keys if k not in taken and k not in TRIBUTES]
            notable = sorted((k for k in open_ if score[k] >= TRIBUTE_NOTABLE), key=lambda k: (-score[k], -legacy_of[k], k))
            queue = sorted(open_, key=lambda k: (-legacy_of[k], k))
            pick = notable[0] if notable else (queue[0] if queue else None)
        if pick is None:
            continue
        taken.add(pick)
        notable_pick = pick in score and score[pick] >= TRIBUTE_NOTABLE
        signals = sorted(sig.get(pick, []), key=lambda x: (-x["weight"], list(TRIBUTE_SIGNALS).index(x["kind"])))
        plan.append({"season": f"Y{y}", "player": pick, "reason": signals[0]["kind"] if notable_pick else "queue",
                     "detail": "; ".join(x["detail"] for x in signals) if notable_pick
                     else "written this season" if locked
                     else f"no one cleared the bar; the queue's highest Career Legacy ({fmt(legacy_of.get(pick, 0))})",
                     "score": score.get(pick, 0), "signals": signals, "written": pick in TRIBUTES})
    return plan


def tribute_queue(candidates: list[dict], plan: list[dict]) -> list[str]:
    """The candidates with no tribute and no season pick, highest Career Legacy first (the fallback order)."""
    planned = {p["player"] for p in plan}
    return [c["key"] for c in candidates if c["key"] not in TRIBUTES and c["key"] not in planned]


def _snap(snap_id: str) -> dict | None:
    return next((s for s in MARKET if s["id"] == snap_id), None)


def _season_snaps() -> list[tuple[str, dict]]:
    """(season, its last market snapshot), oldest first."""
    last: dict[str, dict] = {}
    for s in MARKET:
        y = snapshot_season(s)
        if y:
            last[y] = s
    return sorted(last.items(), key=lambda kv: int(kv[0].lstrip("Y")))


def _card(snap: dict, key: str) -> dict | None:
    pt = snap["players"].get(key)
    if pt is None:
        return None
    pos, _, name = key.partition(":")
    return {"key": key, "name": name, "pos": pos, "ovr": pt.get("ovr"), "grade": pt.get("grade"),
            "value": pt.get("value"), "games": (pt.get("s") or {}).get("g")}


def trade_data(t: dict) -> dict:
    """A trade card: each side's players as the market saw them at `snapshot`, and what each did after (games and
    rings gained by `later`, else the latest snapshot)."""
    at, later = _snap(t["snapshot"]), _snap(t.get("later") or MARKET[-1]["id"])
    sides = []
    for sd in t["sides"]:
        rows = []
        for k in sd["players"]:
            card = _card(at, k) or {"key": k, "name": k.partition(":")[2], "pos": k.partition(":")[0]}
            a, b = (at["players"].get(k) or {}).get("s") or {}, (later["players"].get(k) or {}).get("s") or {}
            card["after"] = {"games": (b.get("g") or 0) - (a.get("g") or 0), "rings": (b.get("rings") or 0) - (a.get("rings") or 0)}
            # moved on before playing a game there (no stint with the club he was traded to)
            card["played"] = sd["to"] in {x["team"] for x in STINTS.get(card["name"], {}).get("stints", [])}
            rows.append(card)
        sides.append({"to": sd["to"], "players": rows, "value": sum(r.get("value") or 0 for r in rows)})
    return {"after": t["after"], "snapshot": at["id"], "label": at.get("label"), "later": later["id"],
            "laterLabel": later.get("label"), "sides": sides}


def market_data(m: dict) -> dict:
    """The value series per season (each season's last snapshot) from the subject's first card: value for every
    player named, plus the subject's OVR and grade."""
    subject = m["players"][0]
    # from his first season on a club's books (stints.json), so an import correction before it isn't a season
    first = min((x["from"] for x in STINTS.get(subject.partition(":")[2], {}).get("stints", [])), default=0)
    series = []
    for y, snap in _season_snaps():
        pt = snap["players"].get(subject)
        if pt is None or int(y.lstrip("Y")) < first:
            continue
        row = {"season": y, "snapshot": snap["id"], "ovr": pt.get("ovr"), "grade": pt.get("grade"),
               "values": {k: snap["players"][k].get("value") for k in m["players"] if k in snap["players"]}}
        series.append(row)
    return {"players": m["players"], "series": series}


RIVAL_RATES = {  # position group -> (label, numerator keys, denominator key, decimals)
    "QB": [("Pass yds a game", ("yds",), "g", 1), ("Pass TDs a game", ("td",), "g", 2)],
    "RB": [("Rush yds a game", ("ryds",), "g", 1), ("TDs a game", ("rtd", "rectd"), "g", 2)],
    "WR": [("Rec yds a game", ("yds",), "g", 1), ("TDs a game", ("td",), "g", 2)],
    "TE": [("Rec yds a game", ("yds",), "g", 1), ("TDs a game", ("td",), "g", 2)],
    "OL": [("Blocks a game", ("blk",), "g", 2)],
    "LB": [("Tackles a game", ("tkl",), "g", 2)], "DB": [("Tackles a game", ("tkl",), "g", 2)], "DL": [("Tackles a game", ("tkl",), "g", 2)],
}


def rival_data(r: dict, key: str) -> dict:
    """The rival card: the two careers side by side from players.json (rates for a shared position, then games,
    rings, MVPs, Super Bowl MVPs and Career Legacy)."""
    by_key = {f'{p["pos"]}:{p["n"]}': p for p in PLAYERS_SRC}
    a, b = by_key[key], by_key[r["player"]]
    rows = []
    if a["pos"] == b["pos"]:
        for label, nums, den, dec in RIVAL_RATES.get(a["pos"], []):
            va = sum(g(a, k) for k in nums) / g(a, den) if g(a, den) else 0
            vb = sum(g(b, k) for k in nums) / g(b, den) if g(b, den) else 0
            rows.append({"label": label, "a": round(va, dec), "b": round(vb, dec), "decimals": dec})
    for label, k in (("Games", "g"), ("Rings", "rings"), ("MVPs", "mvp"), ("Super Bowl MVPs", "sbmvp")):
        rows.append({"label": label, "a": g(a, k), "b": g(b, k), "decimals": 0})
    rows.append({"label": "Career Legacy", "a": legacy(a["n"]), "b": legacy(b["n"]), "decimals": 0})
    return {"player": r["player"], "name": b["n"], "pos": b["pos"], "nickname": b.get("nick"), "rows": rows}


def tribute_out(key: str, t: dict) -> dict:
    """A tribute as the site reads it (src/utils/leagueContent.ts loadTribute): the stored text verbatim, each card's
    figures under the chapter's `data`, the journey of clubs and the hero facts."""
    pos, _, name = key.partition(":")
    p = next(x for x in PLAYERS_SRC if x["n"] == name and x["pos"] == pos)
    journey = [{"team": x["team"], "from": x["from"], "to": x["to"], "rings": x.get("rings", [])}
               for x in STINTS.get(name, {}).get("stints", [])]
    chapters = []
    for c in t["chapters"]:
        c = dict(c)
        if c["kind"] == "trade":
            c["data"] = trade_data(c["trade"])
        elif c["kind"] == "market":
            c["data"] = market_data(c["market"])
        elif c["kind"] == "rival":
            c["data"] = rival_data(c["rival"], key)
        chapters.append(c)
    hof = hall_of_fame.members().get(key)
    hero = {"games": g(p, "g"), "clubs": len({j["team"] for j in journey}), "active": is_status_active(name),
            "careerLegacy": legacy(name), "rings": g(p, "rings"),
            **({"hallOfFame": hof.get("class") or hof.get("classSeason")} if hof else {})}
    return {"key": key, "name": name, "pos": pos, "upload": t.get("upload"),
            **({"nickname": t["nickname"]} if t.get("nickname") else {}),
            "deck": t["deck"], "hero": hero, "journey": journey, "chapters": chapters}


def tribute_index(tributes: list[dict]) -> list[dict]:
    """content.json's Tribute index: who has one, where its file is, and its chapters' headlines."""
    return [{"key": t["key"], "name": t["name"], "file": tribute_file(t["key"]), "upload": t["upload"],
             **({"nickname": t["nickname"]} if t.get("nickname") else {}), "deck": t["deck"],
             "chapters": [{"id": c["id"], "kind": c["kind"], "headline": c["headline"]} for c in t["chapters"]]}
            for t in tributes]


def write_tributes(tributes: list[dict]):
    """public/data/league/tributes/<pos-name>.json, one per tribute; files for players with no tribute are removed."""
    keep = set()
    if tributes:
        TRIBUTES_DIR.mkdir(parents=True, exist_ok=True)
    for t in tributes:
        path = OUT.parent / tribute_file(t["key"])
        keep.add(path.name)
        path.write_text(json.dumps(t, ensure_ascii=False, indent=1) + "\n")
    if TRIBUTES_DIR.exists():
        for old in TRIBUTES_DIR.glob("*.json"):
            if old.name not in keep:
                old.unlink()


