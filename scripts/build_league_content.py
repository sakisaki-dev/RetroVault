def qb_succession():
    """Starting QB by owner season: the best-legacy QB whose dated stint covers that season on the owner's club."""
    qbs = [p for p in LEAGUE if p["pos"] == "QB"]
    by_year = {}
    for y, team in sorted(OWNER.items()):
        on = [p["n"] for p in qbs if (team, y) in set(owner_overlap(p["n"], range(y, y + 1)))]
        if on:
            by_year[y] = sorted(on, key=lambda n: (-legacy(n), n))[0]
    runs: list[list] = []
    for y, n in sorted(by_year.items()):
        if runs and runs[-1][0] == n and runs[-1][2] >= y - 2:
            runs[-1][2] = y
        else:
            runs.append([n, y, y])
    return runs


