def legacy(name: str) -> int:
    return int(round(LEGACY.get(name, 0)))


def team_of(p) -> str | None:
    t = F.TEAM_FIXES.get(p["n"], p.get("team"))
    t = F.CURRENT_CLUB if t == "CUR" else t
    return None if t in (None, "UNK") else t


def dated_stints(name: str) -> list[dict]:
    """Reconstructed stints with real years (placeholder-year careers and post-season trades left out)."""
    s = STINTS.get(name)
    if not s or s.get("approx"):
        return []
    return [x for x in s["stints"] if x["from"] <= LAST]


def owner_overlap(name: str, years: range | None = None) -> list[tuple[str, int]]:
    """(team, year) seasons this player spent on the owner's club."""
    return [(x["team"], y) for x in dated_stints(name) for y in range(x["from"], x["to"] + 1)
            if (x["team"], y) in OWN and (years is None or y in years)]


def fnv1a(text: str) -> int:
    h = 0x811C9DC5
    for b in text.encode("utf-8"):
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def edition() -> dict:
    """Per-update edition: changes whenever an upload is applied (or the season rolls over), never between rebuilds."""
    log_path = SRC / "mutations_log.json"
    applied = json.loads(log_path.read_text()).get("applied", []) if log_path.exists() else []
    last = applied[-1]["id"] if applied else ""
    return {"number": len(applied), "season": SEASON, "upload": last,
            "seed": fnv1a(f"{SEASON}|{len(applied)}|{last}"), "label": f"{SEASON} · Edition {len(applied)}"}


def is_status_active(name: str) -> bool:
    if name in F.STATUS_FIXES:
        return F.STATUS_FIXES[name] == "Active"
    if name in F.ACTIVE_ROSTERS:
        return True
    if name in F.RETIRED_WITH:
        return False
    s = STINTS.get(name, {}).get("stints", [])
    return bool(s) and s[-1]["to"] >= LAST and not STINTS[name].get("approx")


