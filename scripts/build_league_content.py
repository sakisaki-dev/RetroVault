def board_holder_names(holder: str) -> list[str]:
    out = []
    renamed = EXTRAS.get("name_changes", {})
    for part in holder.split("→"):
        part = re.sub(r"\(.*?\)", "", part).strip()
        m = re.match(r"([A-Z]{1,2})\s+([A-Z])\.\s+(.+)$", part)
        if not m:
            continue
        pos, ini, sur = m.groups()
        hits = sorted({renamed.get(n, n) for n in [*BY_NAME, *renamed]
                       if n.startswith(ini) and n.split(" ", 1)[-1] == sur.strip()
                       and BY_NAME.get(renamed.get(n, n), {}).get("pos") == pos})
        out.append(hits[0] if len(hits) == 1 else part)
    return out


