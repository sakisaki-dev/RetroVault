def load(name):
    return json.loads((SRC / name).read_text())


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower().replace("’", "").replace("'", "")).strip("-")


def fmt(n) -> str:
    return f"{n:,}" if isinstance(n, int) else f"{n:,.1f}"


def plural(n: int, one: str, many: str | None = None) -> str:
    return f"{n:,} {one if n == 1 else (many or one + 's')}"


def join(items: list[str]) -> str:
    items = [i for i in items if i]
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1] if items else ""


def year_runs(years: list[int]) -> str:
    ys, out, i = sorted(years), [], 0
    while i < len(ys):
        j = i
        while j + 1 < len(ys) and ys[j + 1] == ys[j] + 1:
            j += 1
        out.append(f"Y{ys[i]}–{ys[j]}" if j > i else f"Y{ys[i]}")
        i = j + 1
    return ", ".join(out)


def longest_run(years: list[int]) -> tuple[int, int, int]:
    """(length, start, end) of the longest run of consecutive years."""
    best, ys = (0, 0, 0), sorted(years)
    i = 0
    while i < len(ys):
        j = i
        while j + 1 < len(ys) and ys[j + 1] == ys[j] + 1:
            j += 1
        if j - i + 1 > best[0]:
            best = (j - i + 1, ys[i], ys[j])
        i = j + 1
    return best


