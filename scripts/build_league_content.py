#!/usr/bin/env python3
"""Build public/data/league/content.json from data/y80. Run from the repo root (npm run rebuild runs it).

Everything here is generated by rules over the data, so it updates itself when the data changes:

* eras        runs of the owner's coaching stints (coach.json), split at long title droughts and merged when a
              stint won fewer than 3 titles; named "<Team> dynasty" (5+ titles), "<Team> run" (3-4) or
              "<Team> years"; key players = best Career Legacy whose stints (stints.json) overlap the era's clubs
* storylines  the Super Bowl ledger, era reports, rivalries, lineages, snubs, outsiders, record chases, iron men,
              one-team legends, plus the owner's own journal notes (data/y80/journal.json, quoted verbatim)
* rivalries   the franchises the owner met most in Super Bowls, with the W-L record and any owner notes
* lineages    family ties (screenshot_extras.json) and the quarterback succession on the owner's clubs
* hofClasses  who first reached the Hall of Fame bar of the season (7000, 7500 from Y85) at each market snapshot (data/y80/market_history.json)
* playerNotes era (derived) and tag: owner tag + family / former name + league records and rate bests
* headlines   "What changed": ranked templated news from the diff between two market snapshots (OVR, skill grade,
              Career Legacy, value and career totals per player) plus the applied bundles' mutations (trades, Super
              Bowls, records): milestones, awards, grade-family changes, market movers, new players, new Hall of
              Famers, plus standing record chases. The latest update's diff when it changed anything, else the last
              update that did (headlinesInfo.scope "Last update")
* edition     the per-update seed: number of applied uploads (data/y80/mutations_log.json), the last one's id and
              the season, hashed (FNV-1a). The site's rotating picks (featured players, hero, headline order, featured
              storylines, pack shelf accent) key off it (src/utils/edition.ts), so each update looks fresh while a
              rebuild of the same data stays byte-identical. Player identity (looks, card art, poses) never uses it.

* rewind      Season Rewind (scripts/season_rewind.py): per completed season, a deck of rule-built cards (cover,
              champion, awards, records, the Gauntlet / milestones, market, Hall of Fame class, farewells, power No. 1
              and upset, tribute pick, the Season Story lead and hottest take quoted, outro) written to
              public/data/league/rewind/<Y>.json, plus seasonRewindIndex

* tributes    Player Tributes (data/y80/tributes.json, tribute.set): each written tribute goes to
              public/data/league/tributes/<pos-name>.json with its figures filled from the data (the journey of clubs
              from stints.json, a trade's sides at the snapshot it names, the market series per season, the rival's
              comparison), plus a tributeIndex. tributeCandidates is the qualification rule (tribute_candidates):
              Career Legacy at the Hall of Fame bar or a Hall of Famer, and at least two of: two clubs or a trade on
              record, a journal mention, a record (club board or league career mark), a rivalry, four of the five award
              kinds, an owner career line. tributePlan picks one candidate per season (tribute_plan: relevance that
              season by weighted signals, at least TRIBUTE_NOTABLE, else the queue's highest Career Legacy; nobody
              twice) and tributeQueue is the fallback order. The latest season's unwritten pick prints TRIBUTE NEEDED.

Career Legacy and OVR come from the latest market snapshot, which `npm run market` computes with the site's own
formulas just before this script runs. Speeches (data/y80/speeches.json), the Season Story
(data/y80/stories.json), the Hot Takes (data/y80/hot_takes.json, written to public/data/league/takes.json) and the
Player Tributes (data/y80/tributes.json) are the only authored text; all pass through unchanged.
"""
